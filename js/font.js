// drawText(ctx, text, x, y, color, scale=1). Handles \n. Returns pixel width of longest line.
export function drawText(ctx, text, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  let cx = x, cy = y, maxw = 0;
  for (const ch of String(text).toUpperCase()) {
    if (ch === '\n') { maxw = Math.max(maxw, cx - x); cx = x; cy += 9 * scale; continue; }
    const g = F[ch] || F[' '];
    for (let r = 0; r < 7; r++) {
      const bits = g[r];
      for (let c = 0; c < 5; c++) {
        if (bits & (0x10 >> c)) ctx.fillRect(cx + c * scale, cy + r * scale, scale, scale);
      }
    }
    cx += 6 * scale;
  }
  return Math.max(maxw, cx - x);
}

export function textWidth(text, scale = 1) {
  let w = 0, max = 0;
  for (const ch of String(text)) { if (ch === '\n') { max = Math.max(max, w); w = 0; } else w += 6 * scale; }
  return Math.max(max, w) - (max || w ? scale : 0);
}
